package Ifexample;

public class SwitchCase3 {
    public static void main(String[] args) {
        String medal = "Gold";
        switch (medal) {
            case "Gold"-> System.out.println("금");

            case "Selver"-> System.out.println("은");

            case "Bronze" ->System.out.println("동");

        }
    }
}
